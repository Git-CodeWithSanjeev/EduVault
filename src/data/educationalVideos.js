export function getVideoId(video) {
  if (!video) return 'tVzUXW6siu0';
  if (typeof video === 'string') return video;
  if (video.videoId) return video.videoId;
  if (video.id && typeof video.id === 'string' && video.id.length === 11 && !video.id.includes('-')) return video.id;
  if (video.thumbnail) {
    const match = video.thumbnail.match(/\/vi\/([a-zA-Z0-9_-]{11})/);
    if (match) return match[1];
  }
  return 'tVzUXW6siu0';
}

export function getPlaylistLessons(vid) {
  if (!vid) return [];
  if (Array.isArray(vid.lessons) && vid.lessons.length > 0) return vid.lessons;
  const mainVidId = getVideoId(vid);
  const count = vid.videoCount || 12;
  return Array.from({ length: Math.min(count, 30) }, (_, i) => ({
    id: i + 1,
    videoId: mainVidId,
    title: `Lesson ${i + 1} — ${vid.title || 'Course Module'} (Part ${i + 1})`,
    duration: `Lesson ${i + 1}`,
  }));
}
